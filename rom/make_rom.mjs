// Build emulator/rom/viper_rom.js from dumps/*.bin and data/*.json so the browser needs no fetch.
// Run from anywhere:  node emulator/rom/make_rom.mjs
// The image SHA-256 is verified; the script refuses to write the bundle if it does not match.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const IMAGE_SHA256 = 'c6f8824050ee6f1412f7b3cbf8ab3d070fa84eea482a5d074f5d9b727c8f5586';

const img = readFileSync(join(root, 'dumps', 'VIPER_04763555_8000-FFFF.bin'));
const ee = readFileSync(join(root, 'dumps', 'VIPER_04763555_eeprom_B600-B7FF.bin'));
const sha = (b) => createHash('sha256').update(b).digest('hex');
if (img.length !== 0x8000) throw new Error(`image is ${img.length} bytes, expected 32768`);
if (ee.length !== 0x200) throw new Error(`eeprom is ${ee.length} bytes, expected 512`);
const imgSha = sha(img);
if (imgSha !== IMAGE_SHA256) throw new Error(`image SHA-256 mismatch: ${imgSha}`);
const eeSha = sha(ee);

const data = {};
for (const name of ['tables', 'io_map', 'ram_symbols', 'sci_commands', 'faults']) {
  data[name] = JSON.parse(readFileSync(join(root, 'data', `${name}.json`), 'utf8'));
}
// code / data split and labels of the disassembly (analysis/code_map.json), for the GUI's disassembly view
{
  const cm = JSON.parse(readFileSync(join(root, 'analysis', 'code_map.json'), 'utf8'));
  data.codemap = { code_ranges: cm.code_ranges, data_ranges: cm.data_ranges, labels: cm.labels };
}

const wrap = (s) => s.replace(/.{1,120}/g, (m) => `  '${m}' +\n`) + "  ''";
const out = `// GENERATED by emulator/rom/make_rom.mjs - do not edit.
// Viper PCM 04763555 flash image (CPU 8000-FFFF), EEPROM (B600-B7FF) and the data/*.json files.
// Image SHA-256 ${imgSha} (verified at build time)
// EEPROM SHA-256 ${eeSha}
// Pure ES module (browser and Node): no fetch, no Node APIs.

export const IMAGE_SHA256 = '${imgSha}';
export const EEPROM_SHA256 = '${eeSha}';

export const IMAGE_B64 =
${wrap(img.toString('base64'))};

export const EEPROM_B64 =
${wrap(ee.toString('base64'))};

const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
/** Decode a base64 string to a Uint8Array (no atob / Buffer dependency). */
export function decodeBase64(s) {
  const lut = new Int16Array(128).fill(-1);
  for (let i = 0; i < 64; i++) lut[B64.charCodeAt(i)] = i;
  const clean = s.replace(/[^A-Za-z0-9+/]/g, '');
  const n = Math.floor(clean.length * 3 / 4);
  const out = new Uint8Array(n);
  let o = 0, acc = 0, bits = 0;
  for (let i = 0; i < clean.length; i++) {
    acc = (acc << 6) | lut[clean.charCodeAt(i)]; bits += 6;
    if (bits >= 8) { bits -= 8; if (o < n) out[o++] = (acc >> bits) & 0xFF; }
  }
  return out;
}

/** Fresh copies of the 32 KB image (index 0 = CPU 8000) and the 512-byte EEPROM (index 0 = B600). */
export function loadImage() { return decodeBase64(IMAGE_B64); }
export function loadEeprom() { return decodeBase64(EEPROM_B64); }

export const DATA = ${JSON.stringify(data)};
`;
writeFileSync(join(here, 'viper_rom.js'), out.replace(/\r\n/g, '\n'));
console.log(`wrote viper_rom.js (${out.length} chars); image SHA-256 OK ${imgSha}`);
